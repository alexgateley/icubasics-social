#!/usr/bin/env node
// Writes video-ctas.json: for every caption in the repo that asks for a comment keyword, the word it asks for, the
// configured keyword it maps to, what the caption promises to send, and what the DM actually sends for that brand.
// Alex 2026-11-24: "we should save what keywords the videos ask for and what they say theyll send".
// Run: node scripts/build-video-ctas.mjs   (--check exits 1 when a caption asks for a word no DM can answer)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { ctaFromCaption, messageFor } from './comment-replies.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG = JSON.parse(fs.readFileSync(path.join(REPO, 'comment-keywords.json'), 'utf8'));
const BRANDS = Object.keys(CONFIG.brandNames);

/** The brand a caption folder belongs to: a brand-named path part (shorts-pm/icu/…, posts-rn/…, published-er/…), else icu. */
function brandOf(rel) {
  for (const part of rel.split('/')) {
    if (BRANDS.includes(part)) return part;
    const suffix = part.match(/^(?:posts|published|shorts|features)-([a-z]+)$/)?.[1];
    if (suffix && BRANDS.includes(suffix)) return suffix;
  }
  return 'icu';
}

const files = execFileSync('git', ['ls-files', '*caption.txt'], { cwd: REPO, encoding: 'utf8' }).split('\n').filter(Boolean);
const videos = {};
const problems = [];
for (const f of files.sort()) {
  const cta = ctaFromCaption(fs.readFileSync(path.join(REPO, f), 'utf8'), CONFIG);
  if (!cta) continue;
  const folder = path.dirname(f);
  const brand = brandOf(folder);
  const dm = cta.keyword ? messageFor(cta.keyword, brand, CONFIG) : null;
  const sends = dm?.match(/https?:\/\/\S+/)?.[0] ?? null;
  videos[folder] = { brand, asks: cta.word, keyword: cta.keyword, promise: cta.promise, sends, label: cta.keyword ? CONFIG.keywords[cta.keyword].label : null };
  if (!cta.keyword) problems.push(`${folder}: asks for ${cta.word}, which is not a keyword or alias`);
  else if (!dm) problems.push(`${folder}: ${cta.word} has no page for ${brand}`);
}

const out = { note: 'Generated by scripts/build-video-ctas.mjs from every caption.txt; do not edit by hand.', count: Object.keys(videos).length, videos };
fs.writeFileSync(path.join(REPO, 'video-ctas.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`video-ctas.json: ${out.count} videos ask for a keyword; ${problems.length} problem(s)`);
for (const p of problems) console.log(`  ${p}`);
if (process.argv.includes('--check') && problems.length) process.exit(1);
